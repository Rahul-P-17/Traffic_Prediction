def make_demand_curve(zone_type_key):
    """
    Build a 24-hour normalised demand curve (0.0–1.0) for a given zone type.
    These curves are SYNTHETIC ASSUMPTIONS based on documented traffic behaviour.
    """
    zt = ZONE_TYPES[zone_type_key]
    peak_hours = zt["peak_periods"]
    base = zt["demand_base"]
    
    # Build smooth curve: start from midnight at low level
    curve = np.ones(24) * 0.08  # overnight minimum
    
    if zone_type_key == "intercity_bus":
        # Broad coverage throughout departure/arrival times
        for h in range(24):
            if 5 <= h <= 8:   curve[h] = 0.90
            elif 9 <= h <= 11: curve[h] = 0.70
            elif 12 <= h <= 14: curve[h] = 0.55
            elif 15 <= h <= 16: curve[h] = 0.65
            elif 17 <= h <= 21: curve[h] = 0.95
            elif 22 <= h <= 23: curve[h] = 0.55
            elif 0 <= h <= 4:   curve[h] = 0.20
    
    elif zone_type_key == "office":
        # Classic bi-modal office commute
        for h in range(24):
            if h in [7, 8]:     curve[h] = 1.00
            elif h in [9]:      curve[h] = 0.85
            elif 10 <= h <= 16: curve[h] = 0.55
            elif h in [17, 18]: curve[h] = 1.00
            elif h in [19]:     curve[h] = 0.80
            elif h in [20, 21]: curve[h] = 0.35
    
    elif zone_type_key == "it_corridor":
        # Slightly delayed relative to office (cab commute, flexi-time)
        for h in range(24):
            if h in [8, 9, 10]: curve[h] = 1.00
            elif 11 <= h <= 17: curve[h] = 0.50
            elif h in [18, 19]: curve[h] = 1.00
            elif h in [20, 21]: curve[h] = 0.75
            elif h in [22, 23]: curve[h] = 0.30
    
    elif zone_type_key == "school":
        # Twin peak: morning drop-off, afternoon pickup
        for h in range(24):
            if h in [7]:        curve[h] = 0.90
            elif h in [8]:      curve[h] = 1.00
            elif h in [9, 10]:  curve[h] = 0.35
            elif 11 <= h <= 12: curve[h] = 0.30
            elif h in [13]:     curve[h] = 0.85
            elif h in [14, 15]: curve[h] = 1.00
            elif h in [16]:     curve[h] = 0.50
            elif h in [17, 18]: curve[h] = 0.40
    
    elif zone_type_key == "shopping":
        # Evening peaks; moderate morning
        for h in range(24):
            if 10 <= h <= 12:   curve[h] = 0.50
            elif 13 <= h <= 15: curve[h] = 0.55
            elif 16 <= h <= 17: curve[h] = 0.70
            elif h in [18, 19]: curve[h] = 1.00
            elif h in [20]:     curve[h] = 0.90
            elif h in [21]:     curve[h] = 0.65
            elif h in [22]:     curve[h] = 0.40
    
    elif zone_type_key == "residential":
        # Departure in morning, return in evening; lower overall
        for h in range(24):
            if h in [7, 8]:     curve[h] = 0.85
            elif h in [9]:      curve[h] = 0.55
            elif 10 <= h <= 16: curve[h] = 0.40
            elif h in [17, 18]: curve[h] = 0.85
            elif h in [19, 20]: curve[h] = 0.65
            elif h in [21]:     curve[h] = 0.45
    
    elif zone_type_key == "highway":
        # Sustained throughput with peaks
        for h in range(24):
            if 5 <= h <= 8:    curve[h] = 0.85
            elif 9 <= h <= 15: curve[h] = 0.70
            elif 16 <= h <= 19: curve[h] = 0.90
            elif 20 <= h <= 22: curve[h] = 0.55
            elif 23 == h or h <= 4: curve[h] = 0.25
    
    elif zone_type_key == "industrial":
        # Three-shift pattern: 6am, 2pm, 10pm
        for h in range(24):
            if h in [5, 6, 7]:   curve[h] = 0.80
            elif h in [13, 14, 15]: curve[h] = 0.80
            elif h in [21, 22, 23]: curve[h] = 0.70
            elif h in [8, 9]:    curve[h] = 0.50
            elif 10 <= h <= 12:  curve[h] = 0.40
            elif 16 <= h <= 20:  curve[h] = 0.45
            elif 0 <= h <= 4:    curve[h] = 0.35
    
    elif zone_type_key == "mixed":
        # Blend of office + shopping
        office_curve = make_demand_curve("office")
        shop_curve = make_demand_curve("shopping")
        curve = (0.6 * office_curve + 0.4 * shop_curve)
    
    return curve

