# Sort chronologically per zone-road
master = master.sort_values(["zone_id", "road_id", "timestamp"]).reset_index(drop=True)

# Lag features (per zone-road group)
grp = master.groupby(["zone_id", "road_id"])
master["lag_1h"] = grp["vehicle_count"].shift(1)
master["lag_2h"] = grp["vehicle_count"].shift(2)
master["lag_3h"] = grp["vehicle_count"].shift(3)
master["lag_6h"] = grp["vehicle_count"].shift(6)
master["lag_24h"] = grp["vehicle_count"].shift(24)

# Rolling means
master["rolling_mean_3h"] = grp["vehicle_count"].transform(
    lambda s: s.rolling(3, min_periods=1).mean())
master["rolling_mean_6h"] = grp["vehicle_count"].transform(
    lambda s: s.rolling(6, min_periods=1).mean())
master["rolling_mean_24h"] = grp["vehicle_count"].transform(
    lambda s: s.rolling(24, min_periods=1).mean())

# Future target (1h ahead) for potential future use — NOT used as input feature
master["future_vehicle_count_1h"] = grp["vehicle_count"].shift(-1)

# Zone type encoding (numeric for ML)
zone_type_map = {zt: i for i, zt in enumerate(ZONE_TYPES.keys())}
master["zone_type_enc"] = master["zone_type"].map(zone_type_map)

# Road capacity normalised
