def generate_weather(timestamps, rng):
    """
    Generate a realistic hourly weather series for Chennai.
    Weather persists in blocks (rain lasts hours, not isolated minutes).
    """
    n = len(timestamps)
    weather_types = list(WEATHER_PROFILES.keys())
    
    weather = []
    i = 0
    while i < n:
        month = timestamps[i].month
        probs_dict = MONTHLY_WEATHER_PROB[month]
        wt_list = list(probs_dict.keys())
        probs = [probs_dict[w] for w in wt_list]
        chosen = rng.choice(wt_list, p=probs)
        
        # Weather persists for 1-6 hours (block generation)
        if chosen == "clear":
            duration = int(rng.integers(2, 12))
        elif chosen == "light_rain":
            duration = int(rng.integers(2, 6))
        elif chosen == "moderate_rain":
            duration = int(rng.integers(2, 5))
        else:
            duration = int(rng.integers(1, 4))
        
        for _ in range(duration):
            if i < n:
                weather.append(chosen)
                i += 1
    
    return weather[:n]

