def generate_zone_road_records(zone, road, timestamps, weather_df, festival_lookup, rng, zone_rng_offset):
    """
    Generate hourly traffic records for a single zone-road combination.
    
    DATA CLASSIFICATION: SYNTHETIC — all values computed from behavioural rules
    + documented multipliers + controlled stochastic noise.
    """
    zt_key = zone["zone_type"]
    zt = ZONE_TYPES[zt_key]
    demand_curve = DEMAND_CURVES[zt_key]
    capacity = road["capacity"]
    
    records = []
    rng_local = np.random.default_rng(SEED + zone_rng_offset)
    
    for ts in timestamps:
        h = ts.hour
        dow = ts.dayofweek  # 0=Mon, 6=Sun
        month = ts.month
        is_weekend = 1 if dow >= 5 else 0
        is_weekday = 1 - is_weekend
        date_str = str(ts.date())
        
        # --- Base demand from demand curve ---
        base_demand = demand_curve[h]
        
        # --- Weekend adjustment ---
        wf = zt["weekend_factor"]
        if is_weekend:
            base_demand = base_demand * wf
        
        # --- School activity ---
        school_month_active, _ = TN_SCHOOL_HOLIDAYS[month]
        school_active = int(
            school_month_active and is_weekday and
            (h in SCHOOL_HOURS_ARRIVAL or h in SCHOOL_HOURS_DEPARTURE)
        )
        if zt["school_influence"] and school_active:
            base_demand = min(base_demand * 1.45, 1.0)
        # School zones less busy during holidays
        if zt_key == "school" and not school_month_active:
            base_demand = base_demand * 0.30
        
        # --- Office activity ---
        office_active = int(
            is_weekday and h in [8, 9, 17, 18, 19]
        )
        
        # --- Shopping activity ---
        shopping_active = int(h in [11, 12, 17, 18, 19, 20] and (is_weekend or h >= 17))
        
        # --- Festival effects ---
        festival_name = "None"
        festival_phase = "None"
        festival_multiplier = 1.0
        if date_str in festival_lookup:
            # Use first festival if multiple (rare edge case)
            fest_info = festival_lookup[date_str][0]
            festival_name = fest_info["festival_name"]
            festival_phase = fest_info["phase"]
            zone_type_mults = fest_info["multipliers"]
            festival_multiplier = zone_type_mults.get(zt_key, 1.0)
            base_demand = base_demand * festival_multiplier
        
        festival_flag = int(festival_name != "None")
        festival_proximity = {
            "day_before": 1, "festival_day": 2, "day_after": 1, "None": 0
        }.get(festival_phase, 0)
        
        # --- Weather effects ---
        w_row = weather_df.loc[ts]
        weather_cond = w_row["weather_condition"]
        demand_factor = w_row["demand_factor"]
        speed_factor = w_row["speed_factor"]
        capacity_factor = w_row["capacity_factor"]
        rain_mm = w_row["rain_mm_per_hr"]
        temperature = w_row["temperature"]
        
        # Weather-sensitive zones are more affected
        ws = zt["weather_sensitivity"]
        # Blend: full demand_factor for highly sensitive, partial for low-sensitivity
        effective_demand_factor = 1.0 - (1.0 - demand_factor) * ws
        base_demand = base_demand * effective_demand_factor
        
        # --- Public transport activity index (SYNTHETIC, correlated with peak hour) ---
        pt_base = 0.25
        if h in [7, 8, 9, 17, 18, 19]:
            pt_base = 0.65
        elif h in [10, 11, 12, 13, 14, 15, 16]:
            pt_base = 0.40
        # Bus zones have higher PT activity
        if zt_key == "intercity_bus":
            pt_base = min(pt_base * 1.4, 1.0)
        syn_public_transport = float(np.clip(
            pt_base + rng_local.normal(0, 0.06), 0.05, 1.0))
        
        # --- Parking occupancy (SYNTHETIC, correlated with zone type + hour) ---
        if zt_key == "shopping":
            park_base = 0.20 + 0.60 * demand_curve[h]
        elif zt_key in ("office", "it_corridor"):
            park_base = 0.10 + 0.70 * demand_curve[h] * is_weekday
        elif zt_key == "residential":
            # Residential: high overnight, lower during day
            park_base = 0.70 - 0.50 * demand_curve[h]
        else:
            park_base = 0.30 + 0.30 * demand_curve[h]
        park_base = min(park_base * festival_multiplier, 1.0) if festival_flag else park_base
        syn_parking_occupancy = float(np.clip(
            park_base + rng_local.normal(0, 0.05), 0.0, 1.0))
        
        # --- Accident (SYNTHETIC, sparse — ~0.3% hourly probability per road) ---
        accident_flag = int(rng_local.random() < 0.003)
        accident_severity = float(round(rng_local.uniform(0.3, 1.0), 2)) if accident_flag else 0.0
        if accident_flag:
            # Accidents reduce effective capacity
            capacity_factor = max(capacity_factor - accident_severity * 0.25, 0.3)
            speed_factor = max(speed_factor - accident_severity * 0.20, 0.2)
        
        # --- Construction (SYNTHETIC, sparse — certain dates affect capacity) ---
        construction_flag = 0
        construction_impact = 0.0
        # Construction seed: use zone+road ID hash for deterministic placement
        road_seed = int(hashlib.md5(
            f"{zone['zone_id']}_{road['road_id']}".encode()).hexdigest(), 16) % 1000
        # ~10 construction days spread across the year
        construction_day_of_year = ts.timetuple().tm_yday
        if (road_seed + construction_day_of_year) % 37 == 0:  # sparse pattern
            construction_flag = 1
            construction_impact = round(float(rng_local.uniform(0.15, 0.50)), 2)
            capacity_factor = max(capacity_factor - construction_impact * 0.3, 0.4)
        
        # --- Traffic volume calculation ---
        effective_capacity = capacity * capacity_factor
        # Base volume = demand fraction × effective capacity
        base_volume = base_demand * effective_capacity
        
        # Controlled Gaussian noise (±6% coefficient of variation)
        noise = rng_local.normal(1.0, 0.06)
        volume = max(int(round(base_volume * noise)), 5)
        
        # Clamp to realistic range
        volume = min(volume, int(capacity * 1.15))  # allow slight oversaturation
        
        # --- Average speed ---
        # Base speed depends on road type and congestion
        base_speeds = {
            "national_highway": 65.0,
            "state_highway": 50.0,
            "ring_road": 45.0,
            "arterial": 35.0,
            "minor": 25.0,
        }
        base_speed = base_speeds.get(road.get("road_type", "arterial"), 35.0)
        # Speed reduces as volume approaches capacity (BPR function approximation)
        v_c_ratio = min(volume / max(effective_capacity, 1), 1.2)
        congestion_speed_factor = 1.0 / (1.0 + 0.15 * v_c_ratio ** 4)
        avg_speed = round(
            base_speed * speed_factor * congestion_speed_factor
            * rng_local.normal(1.0, 0.04),
            1
        )
        avg_speed = max(avg_speed, 5.0)
        
        # --- Congestion level ---
        vc = volume / max(road["capacity"], 1)
        if vc < 0.40:
            congestion_level = "LOW"
        elif vc < 0.75:
            congestion_level = "MODERATE"
        else:
            congestion_level = "HEAVY"
        
        records.append({
            # Identifiers
            "zone_id": zone["zone_id"],
            "zone_name": zone["zone_name"],
            "zone_type": zt_key,
            "road_id": road["road_id"],
            "road_name": road["road_name"],
            "road_capacity": road["capacity"],
            "timestamp": ts,
            
            # Traffic
            "vehicle_count": volume,
            "average_speed": avg_speed,
            "congestion_level": congestion_level,
            
            # Temporal features
            "hour": h,
            "day_of_week": dow,
            "is_weekend": is_weekend,
            "month": month,
            "season": (month % 12) // 3,  # 0=winter,1=spring,2=summer,3=fall
            "day_of_year": ts.timetuple().tm_yday,
            
            # Weather
            "weather_condition": weather_cond,
            "rain_mm_per_hr": float(rain_mm),
            "temperature": float(temperature),
            "speed_factor_weather": float(round(speed_factor, 3)),
            "capacity_factor_weather": float(round(capacity_factor, 3)),
            
            # Festival
            "festival_flag": festival_flag,
            "festival_name": festival_name,
            "festival_phase": festival_phase,
            "festival_proximity": festival_proximity,
            "festival_multiplier": round(festival_multiplier, 3),
            
            # Activity
            "school_activity": school_active,
            "office_activity": office_active,
            "shopping_activity": shopping_active,
            
            # Synthetic contextual
            "syn_public_transport_activity": round(syn_public_transport, 3),
            "syn_parking_occupancy": round(syn_parking_occupancy, 3),
            "syn_accident_flag": accident_flag,
            "syn_accident_severity": accident_severity,
            "syn_construction_flag": construction_flag,
            "syn_construction_impact": construction_impact,
            
            # Data provenance
            "source_type": "SYNTHETIC",
            "data_quality": "MEDIUM",
            "generated_flag": 1,
        })
    
    return records

all_records = []
