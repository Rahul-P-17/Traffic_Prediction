def build_festival_lookup(festival_calendar, year):
    """
    Returns a dict: date_str -> {festival_name, phase, multipliers}
    Covers day_before, festival_day, day_after for each festival.
    """
    lookup = {}
    key = f"dates_{year}"
    for fname, fdata in festival_calendar.items():
        if key not in fdata:
            continue
        for date_str in fdata[key]:
            fest_date = datetime.strptime(date_str, "%Y-%m-%d").date()
            day_before = fest_date - timedelta(days=1)
            day_after = fest_date + timedelta(days=1)
            
            if str(day_before) not in lookup:
                lookup[str(day_before)] = []
            lookup[str(day_before)].append({
                "festival_name": fname,
                "phase": "day_before",
                "multipliers": fdata["multipliers"]["day_before"],
                "peak_hour_shift": fdata.get("peak_hour_shift", {}),
            })
            
            if str(fest_date) not in lookup:
                lookup[str(fest_date)] = []
            lookup[str(fest_date)].append({
                "festival_name": fname,
                "phase": "festival_day",
                "multipliers": fdata["multipliers"]["festival_day"],
                "peak_hour_shift": fdata.get("peak_hour_shift", {}),
            })
            
            if str(day_after) not in lookup:
                lookup[str(day_after)] = []
            lookup[str(day_after)].append({
                "festival_name": fname,
                "phase": "day_after",
                "multipliers": fdata["multipliers"]["day_after"],
                "peak_hour_shift": fdata.get("peak_hour_shift", {}),
            })
    
    return lookup

