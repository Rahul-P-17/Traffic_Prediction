"""
Feature store for /predict_live.

WHY THIS FILE EXISTS
---------------------
Before this fix, /predict_live built its 32-value feature vector by
hand: weather, accident, and construction features were hardcoded
constants (rain=0, weather factors=1.0, accident/construction=0), and
all five lag/rolling features were the placeholder `road.capacity * 0.6`
for every single request. That made the endpoint blind to weather,
accidents, construction, and — because lag_24h and rolling_mean_3h are
the two most important features to the trained model (44% and 17% of
total gain respectively) — largely blind to genuine temporal dynamics
too.

The project already contains real hourly synthetic history for every
zone/road for all of calendar year 2025
(data/processed/chennai_master.parquet), generated by
scripts/build_pipeline.py with a documented, seeded generative process
(weather blocks, festival multipliers, sparse accident/construction
events, and lag/rolling features computed by an actual groupby+shift
over the true time series). That is the correct, non-arbitrary source
for every one of those features — so we look them up, instead of
inventing new numbers.

WHAT THIS PROVIDES
-------------------
get_context_row(zone_id, road_id, dt) returns the exact FEATURES
vector (in feature_config.FEATURES order) for that zone/road at that
hour, taken directly from the generated dataset, plus metadata
(matched weather condition, festival name/phase, whether a fallback
was used, and the actual historical vehicle count for that hour so the
response can show ground truth alongside the model's prediction).

apply_scenario_override(feat, meta, zone_id, road_id, scenario) swaps
in weather/accident/construction feature values from a REAL historical
hour for that same road that actually experienced the requested
condition (e.g. "heavy_rain", "accident", "construction"), so what-if
testing still uses only values the generator actually produced —
never invented numbers, and never a change applied to the model's
*output*.
"""
import os
import sys
import datetime
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
from feature_config import FEATURES  # noqa: E402

PARQUET_PATH = os.path.join(ROOT, "data", "processed", "chennai_master.parquet")

_df = None
_index = None
_year_min = None
_year_max = None
_scenario_cache = {}


def _load():
    global _df, _index, _year_min, _year_max
    if _df is not None:
        return
    df = pd.read_parquet(PARQUET_PATH)
    df["timestamp"] = pd.to_datetime(df["timestamp"])
    df = df.sort_values(["zone_id", "road_id", "timestamp"]).reset_index(drop=True)
    _df = df
    idx = {}
    for row in df.itertuples(index=False):
        idx[(row.zone_id, row.road_id, row.timestamp)] = row
    _index = idx
    _year_min = df["timestamp"].min()
    _year_max = df["timestamp"].max()


def _row_to_features(row):
    return {f: float(getattr(row, f)) for f in FEATURES}


def get_context_row(zone_id: str, road_id: str, dt: datetime.datetime):
    """
    Returns (feature_dict, meta_dict) or (None, meta_dict_with_error).

    feature_dict has exactly the keys/order needed to build the model
    input (caller still assembles it via feature_config.FEATURES to
    keep ordering explicit at the call site).
    """
    _load()
    dt_hour = pd.Timestamp(dt).replace(minute=0, second=0, microsecond=0)

    fallback = False
    fallback_reason = None
    lookup_dt = dt_hour
    if not (_year_min <= dt_hour <= _year_max):
        fallback = True
        try:
            lookup_dt = dt_hour.replace(year=_year_min.year)
        except ValueError:
            # Feb 29 on a non-leap dataset year etc.
            lookup_dt = dt_hour.replace(year=_year_min.year, day=28)
        # The year-substituted date can still fall outside the dataset's
        # actual window (e.g. requesting Jan 1 when the simulated year
        # starts Jan 2 — a real gap in this dataset, see DATA_PROVENANCE.md).
        # Clamp to the nearest boundary IN THE CORRECT DIRECTION, preserving
        # the requested hour-of-day, rather than blindly stepping backward
        # (which used to walk the date further out of range instead of into
        # it — the actual cause of forecast rows silently disappearing for
        # any horizon date that substituted to Jan 1).
        if lookup_dt < _year_min:
            lookup_dt = _year_min.normalize() + pd.Timedelta(hours=dt_hour.hour)
        elif lookup_dt > _year_max:
            lookup_dt = _year_max.normalize() + pd.Timedelta(hours=dt_hour.hour)
        fallback_reason = (
            f"Requested date {dt_hour.date()} is outside the simulated "
            f"dataset window ({_year_min.date()} to {_year_max.date()}). "
            f"Falling back to the same month/day/hour in {_year_min.year} "
            f"as a documented substitute — the day-of-week and any "
            f"festival alignment for that specific requested year are NOT "
            f"guaranteed to match."
        )

    row = _index.get((zone_id, road_id, lookup_dt))
    if row is None:
        return None, {
            "error": f"No historical/synthetic record found for {zone_id}/{road_id} at {lookup_dt}",
            "is_fallback": fallback,
        }

    feat = _row_to_features(row)
    meta = {
        "requested_timestamp": str(dt),
        "matched_timestamp": str(row.timestamp),
        "is_fallback": fallback,
        "fallback_reason": fallback_reason,
        "weather_condition": row.weather_condition,
        "festival_name": row.festival_name,
        "festival_phase": row.festival_phase,
        "actual_historical_vehicle_count": float(row.vehicle_count),
        "actual_historical_congestion_level": row.congestion_level,
    }
    return feat, meta


_SCENARIO_WEATHER_MAP = {
    "clear": "clear",
    "light_rain": "light_rain",
    "moderate_rain": "moderate_rain",
    "rain": "moderate_rain",
    "heavy_rain": "heavy_rain",
    "very_heavy_rain": "very_heavy_rain",
}
_WEATHER_FEATURES = ["rain_mm_per_hr", "speed_factor_weather", "capacity_factor_weather"]


def _find_real_row_with_condition(zone_id, road_id, dt_hour, predicate):
    """
    Search outward in time (+/- hours, capped) around dt_hour, within the
    same zone/road, for the closest REAL historical hour matching
    `predicate(row) -> bool`. Returns the matched row or None.
    """
    _load()
    same_zr = _df[(_df.zone_id == zone_id) & (_df.road_id == road_id)]
    if same_zr.empty:
        return None
    candidates = same_zr[same_zr.apply(predicate, axis=1)]
    if candidates.empty:
        return None
    # Closest hour-of-day to the requested time, for a like-for-like comparison
    target_hour = dt_hour.hour
    candidates = candidates.copy()
    candidates["_hour_dist"] = (candidates["hour"] - target_hour).abs()
    candidates = candidates.sort_values("_hour_dist")
    return candidates.iloc[0]


def apply_scenario_override(feat: dict, meta: dict, zone_id: str, road_id: str,
                             dt: datetime.datetime, scenario: str):
    """
    Mutates a COPY of `feat` by swapping in real, dataset-derived values
    for the requested what-if scenario. Never touches the model's
    prediction directly — only its input features. Returns (new_feat, note).
    """
    if not scenario or scenario == "normal":
        return dict(feat), None

    dt_hour = pd.Timestamp(dt).replace(minute=0, second=0, microsecond=0)
    new_feat = dict(feat)

    if scenario in _SCENARIO_WEATHER_MAP:
        cond = _SCENARIO_WEATHER_MAP[scenario]
        row = _find_real_row_with_condition(
            zone_id, road_id, dt_hour,
            lambda r, c=cond: r["weather_condition"] == c,
        )
        if row is None:
            return new_feat, f"No historical hour with weather_condition='{cond}' found for {zone_id}/{road_id}; scenario not applied."
        for f in _WEATHER_FEATURES:
            new_feat[f] = float(row[f])
        return new_feat, (
            f"Weather overridden to '{cond}' using the real synthetic hour "
            f"{row['timestamp']} for {zone_id}/{road_id} "
            f"(rain_mm_per_hr={row['rain_mm_per_hr']}, "
            f"speed_factor_weather={row['speed_factor_weather']}, "
            f"capacity_factor_weather={row['capacity_factor_weather']})."
        )

    if scenario == "accident":
        row = _find_real_row_with_condition(
            zone_id, road_id, dt_hour, lambda r: r["syn_accident_flag"] == 1,
        )
        if row is None:
            return new_feat, f"No historical accident-flagged hour found for {zone_id}/{road_id}; scenario not applied."
        new_feat["syn_accident_flag"] = float(row["syn_accident_flag"])
        new_feat["syn_accident_severity"] = float(row["syn_accident_severity"])
        # An accident also degrades the effective weather/capacity factors
        # in the generator (see build_pipeline.py); carry that through too.
        new_feat["speed_factor_weather"] = float(row["speed_factor_weather"])
        new_feat["capacity_factor_weather"] = float(row["capacity_factor_weather"])
        return new_feat, (
            f"Accident scenario applied using the real synthetic hour "
            f"{row['timestamp']} for {zone_id}/{road_id} "
            f"(syn_accident_severity={row['syn_accident_severity']})."
        )

    if scenario == "construction":
        row = _find_real_row_with_condition(
            zone_id, road_id, dt_hour, lambda r: r["syn_construction_flag"] == 1,
        )
        if row is None:
            return new_feat, f"No historical construction-flagged hour found for {zone_id}/{road_id}; scenario not applied."
        new_feat["syn_construction_flag"] = float(row["syn_construction_flag"])
        new_feat["syn_construction_impact"] = float(row["syn_construction_impact"])
        new_feat["capacity_factor_weather"] = float(row["capacity_factor_weather"])
        return new_feat, (
            f"Construction scenario applied using the real synthetic hour "
            f"{row['timestamp']} for {zone_id}/{road_id} "
            f"(syn_construction_impact={row['syn_construction_impact']})."
        )

    return new_feat, f"Unknown scenario '{scenario}'; no override applied."
